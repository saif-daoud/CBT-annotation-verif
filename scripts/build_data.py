"""Build the private seed for the verification study: 2 sessions with the TOPAS automatic labels on every turn.

Inputs : ../cbt-annotation/data/sessions.json (selected Alexander Street transcripts, private)
         ../../annotations_topas/annotations_macro_actions.csv and annotations_micro_actions.csv
Outputs: data/sessions.json and data/seed.sql (PRIVATE, git-ignored; load with `npm run db:seed:remote`)

Each turn gets the macro action of the TOPAS phase it falls in (phases span therapist utterances; patient turns
between phases go with the preceding phase, the opening patient turn with phase 1). Therapist turns also get the
TOPAS micro action ("None" is a real TOPAS label, so the CSVs are read with keep_default_na=False).
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TOPAS = ROOT.parents[1]
SESSIONS = ["S01", "S02"]

source = {s["id"]: s for s in json.loads((TOPAS / "interface/cbt-annotation/data/sessions.json").read_text(encoding="utf-8"))}
ann = TOPAS / "annotations_topas"
macro_df = pd.read_csv(ann / "annotations_macro_actions.csv", keep_default_na=False)
micro_df = pd.read_csv(ann / "annotations_micro_actions.csv", keep_default_na=False)


def sql(value):
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


out, lines = [], ["-- Generated by scripts/build_data.py. Contains licensed transcripts: never commit.",
                  "DELETE FROM session_turns;", "DELETE FROM sessions;"]
for order, sid in enumerate(SESSIONS, start=1):
    s = source[sid]
    u, k, turns = s["user_idx"], s["session_idx"], s["turns"]
    mac = macro_df.query("user_idx == @u and session_idx == @k").sort_values("from_idx")
    mic = micro_df.query("user_idx == @u and session_idx == @k")
    therapist = [t for t in turns if t["speaker"] == "therapist"]
    # sanity: TOPAS rows must line up with this transcript
    assert list(mic.sort_values("utterance_idx").utterance_id) == [t["utterance_id"] for t in therapist], sid
    assert list(mic.sort_values("utterance_idx").utterance_idx) == [t["turn_index"] for t in therapist], sid
    starts = mac["from_idx"].tolist()
    phase_of, macro_of = {}, {}
    for i, (_, ph) in enumerate(mac.iterrows()):
        lo = 0 if i == 0 else int(ph["from_idx"])
        hi = int(starts[i + 1]) - 1 if i + 1 < len(starts) else len(turns) - 1
        for t in range(lo, hi + 1):
            phase_of[t], macro_of[t] = i, ph["selected_macro_action"]
    micro_of = dict(zip(mic["utterance_idx"].astype(int), mic["selected_micro_action"]))
    labelled = []
    for t in turns:
        labelled.append({**t, "phase_index": phase_of[t["turn_index"]], "macro_action": macro_of[t["turn_index"]],
                         "micro_action": micro_of.get(t["turn_index"]) if t["speaker"] == "therapist" else None})
    out.append({k2: s[k2] for k2 in ("id", "user_idx", "session_idx", "patient", "title", "summary", "conditions",
                                     "therapist_turns", "patient_turns", "word_count")} | {"display_order": order, "turns": labelled})
    lines.append("INSERT INTO sessions (id, display_order, user_idx, session_idx, patient, title, summary, conditions_json, "
                 "therapist_turns, patient_turns, word_count) VALUES (" + ", ".join(sql(v) for v in (
                     sid, order, u, k, s["patient"], s["title"], s["summary"], json.dumps(s["conditions"], ensure_ascii=False),
                     s["therapist_turns"], s["patient_turns"], s["word_count"])) + ");")
    for t in labelled:
        lines.append("INSERT INTO session_turns (session_id, turn_index, speaker, utterance_id, text, phase_index, macro_action, micro_action) VALUES ("
                     + ", ".join(sql(v) for v in (sid, t["turn_index"], t["speaker"], t["utterance_id"], t["text"],
                                                  t["phase_index"], t["macro_action"], t["micro_action"])) + ");")
    print(f"{sid}: dataset user {u}, session {k}; {len(turns)} turns, {len(therapist)} therapist turns, {len(mac)} TOPAS phases, "
          f"{sum(1 for t in labelled if t['micro_action'] == 'None')} 'None' micro labels")

(ROOT / "data").mkdir(exist_ok=True)
(ROOT / "data/sessions.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
(ROOT / "data/seed.sql").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote data/sessions.json and data/seed.sql")
